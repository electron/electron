#!/usr/bin/env python3

import argparse
import concurrent.futures
import difflib
import os
import pathlib
import re
import subprocess
import sys


FUNCTION_RE = re.compile(
    r'^define\b.*?@(?:"(?P<quoted>[^"]+)"|(?P<plain>[^( ]+))\('
)
INDIRECT_CALL_RE = re.compile(
    r'\b(?:call|invoke)\b(?![^\n]*\basm\b)[^@\n]*?\s%[-a-zA-Z$._0-9]+\s*\('
)
CFI_TYPE_TEST_RE = re.compile(r'@llvm\.type\.test\(')
CFI_ICALL_TYPE_TEST_RE = re.compile(
    r'@llvm\.type\.test\([^,\n]+,\s*metadata\s*!"_ZTSF'
)
CFI_VCALL_TYPE_TEST_RE = re.compile(
    r'@llvm\.type\.test\([^,\n]+,\s*metadata\s*!"all-vtables"'
)
MODULE_HASH_RE = re.compile(r'\.[0-9a-f]{32}(?=\.|$)')
MANIFEST_HEADER = (
    '# Generated by build/cfi/verify_callback_boundaries.py --update.\n'
    '# Contains protected cfi-icall sites and inferred unchecked indirect '
    'calls.\n'
    '# Review every change; unchecked addon dispatchers must remain narrow.\n'
)
REQUIRED_BOUNDARIES = {
    'V8 use-counter addon dispatcher is unchecked': (
        'v8/',
        '/isolate.o\t',
        'CountUsage',
        'unchecked_calls=1\ticall_checks=0',
    ),
    'V8 dynamic-import addon dispatcher is unchecked': (
        'v8/',
        '/isolate.o\t',
        'RunHostImportModuleDynamicallyCallback',
        'icall_checks=0',
    ),
    'V8 import-meta addon dispatcher is unchecked': (
        'v8/',
        '/isolate.o\t',
        'RunHostInitializeImportMetaObjectCallback',
        'unchecked_calls=1\ticall_checks=0',
    ),
    'V8 unrelated callback remains protected': (
        'v8/',
        '/isolate.o\t',
        'CreateMessageOrAbort',
        'unchecked_calls=0\ticall_checks=1',
    ),
    'libuv addon work dispatcher is unchecked': (
        'libuv/threadpool.o\tuv__queue_work.<module>',
        'unchecked_calls=1\ticall_checks=0',
    ),
    'libuv addon completion dispatcher is unchecked': (
        'libuv/threadpool.o\tuv__queue_done.<module>',
        'unchecked_calls=1\ticall_checks=0',
    ),
    'libuv internal work dispatcher remains protected': (
        'libuv/threadpool.o\tuv__work_done',
        'unchecked_calls=0\ticall_checks=1',
    ),
}


def parse_named_path(value):
    try:
        name, path = value.split('=', 1)
    except ValueError as error:
        raise argparse.ArgumentTypeError('expected NAME=PATH') from error
    if not name or not path:
        raise argparse.ArgumentTypeError('expected non-empty NAME=PATH')
    return name, pathlib.Path(path)


def parse_ninja_objects(value):
    try:
        named_path, target = value.split('::', 1)
        name, path = parse_named_path(named_path)
    except (ValueError, argparse.ArgumentTypeError) as error:
        raise argparse.ArgumentTypeError(
            'expected NAME=PATH::NINJA_TARGET'
        ) from error
    if not target:
        raise argparse.ArgumentTypeError('expected a non-empty Ninja target')
    return name, path, target


def run(command, *, input_bytes=None):
    result = subprocess.run(
        command,
        input=input_bytes,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode != 0:
        sys.stderr.buffer.write(result.stderr)
        raise RuntimeError(f'command failed: {" ".join(map(str, command))}')
    return result.stdout


def disassemble(clang, object_path):
    return run([
        clang,
        '-x',
        'ir',
        '-S',
        '-emit-llvm',
        object_path,
        '-o',
        '-',
    ]).decode()


def read_ninja_objects(build_dir, ninja_file, target):
    contents = re.sub(r'\$\r?\n\s*', '', ninja_file.read_text())
    prefix = f'build {target}: phony '
    for line in contents.splitlines():
        if line.startswith(prefix):
            dependencies = line[len(prefix):].split('|', 1)[0].split()
            objects = [
                build_dir / dependency
                for dependency in dependencies
                if dependency.endswith('.o')
            ]
            if not objects:
                raise RuntimeError(
                    f'Ninja target has no object dependencies: {target}'
                )
            return objects
    raise RuntimeError(f'Ninja target not found in {ninja_file}: {target}')


def find_thin_archive_member(archive, member):
    member_path = pathlib.Path(member)
    candidates = [
        member_path,
        archive.parent / member_path,
        archive.parent / 'uv' / member_path.name,
    ]
    parts = member_path.parts
    if 'obj' in parts:
        obj_index = parts.index('obj')
        root_out_dir = archive
        while root_out_dir.name != 'obj':
            if root_out_dir.parent == root_out_dir:
                break
            root_out_dir = root_out_dir.parent
        if root_out_dir.name == 'obj':
            candidates.append(root_out_dir.parent.joinpath(*parts[obj_index:]))
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise RuntimeError(
        f'cannot resolve thin archive member {member!r} from {archive}'
    )


def inventory_module(label, llvm_ir):
    rows = []
    function_name = None
    body = []

    def finish_function():
        if function_name is None:
            return
        function_body = '\n'.join(body)
        indirect_calls = len(INDIRECT_CALL_RE.findall(function_body))
        type_tests = len(CFI_TYPE_TEST_RE.findall(function_body))
        icall_checks = len(CFI_ICALL_TYPE_TEST_RE.findall(function_body))
        vcall_checks = len(CFI_VCALL_TYPE_TEST_RE.findall(function_body))
        unchecked_calls = max(
            0, indirect_calls - icall_checks - vcall_checks
        )
        if unchecked_calls or icall_checks:
            normalized_name = MODULE_HASH_RE.sub('.<module>', function_name)
            rows.append(
                f'{label}\t{normalized_name}\t'
                f'indirect_calls={indirect_calls}\t'
                f'unchecked_calls={unchecked_calls}\t'
                f'icall_checks={icall_checks}'
            )
        if icall_checks + vcall_checks > type_tests:
            raise RuntimeError(
                f'invalid CFI check counts in {label}:{function_name}'
            )

    for line in llvm_ir.splitlines():
        match = FUNCTION_RE.match(line)
        if match:
            finish_function()
            function_name = match.group('quoted') or match.group('plain')
            body = []
        elif function_name is not None:
            if line == '}':
                finish_function()
                function_name = None
                body = []
            else:
                body.append(line)
    finish_function()
    return rows


def verify_inventory_classifier():
    def function_ir(body):
        return f'''define void @test(ptr %callback, ptr %vtable) {{
entry:
{body}
  ret void
}}
'''

    cases = {
        'unchecked indirect call': (
            '  call void %callback()',
            'indirect_calls=1\tunchecked_calls=1\ticall_checks=0',
        ),
        'protected icall': (
            '  %valid = call i1 @llvm.type.test('
            'ptr %callback, metadata !"_ZTSFvvE")\n'
            '  call void %callback()',
            'indirect_calls=1\tunchecked_calls=0\ticall_checks=1',
        ),
        'vcall-only function': (
            '  %specific = call i1 @llvm.type.test('
            'ptr %vtable, metadata !"_ZTSN4TestE")\n'
            '  %valid = call i1 @llvm.type.test('
            'ptr %vtable, metadata !"all-vtables")\n'
            '  call void %callback()',
            None,
        ),
        'unchecked call next to a vcall': (
            '  %specific = call i1 @llvm.type.test('
            'ptr %vtable, metadata !"_ZTSN4TestE")\n'
            '  %valid = call i1 @llvm.type.test('
            'ptr %vtable, metadata !"all-vtables")\n'
            '  call void %callback()\n'
            '  call void %callback()',
            'indirect_calls=2\tunchecked_calls=1\ticall_checks=0',
        ),
    }
    errors = []
    for description, (body, expected_counts) in cases.items():
        rows = inventory_module('self-test.o', function_ir(body))
        if expected_counts is None:
            passed = not rows
        else:
            passed = len(rows) == 1 and expected_counts in rows[0]
        if not passed:
            errors.append(f'{description}: got {rows!r}')
    if errors:
        raise RuntimeError(
            'CFI inventory classifier sanity checks failed:\n- ' +
            '\n- '.join(errors)
        )


def build_inventory(args):
    modules = list(args.object)
    dependencies = [path for _, path in args.object]

    for label, ninja_file, target in args.ninja_objects:
        dependencies.append(ninja_file)
        object_paths = read_ninja_objects(args.build_dir, ninja_file, target)
        dependencies.extend(object_paths)
        modules.extend(
            (f'{label}/{object_path.relative_to(args.build_dir)}', object_path)
            for object_path in object_paths
        )

    for archive_label, archive_path in args.thin_archive:
        members = run([args.llvm_ar, 't', archive_path]).decode().splitlines()
        if not members:
            raise RuntimeError(f'thin archive is empty: {archive_path}')
        for member in members:
            object_path = find_thin_archive_member(archive_path, member)
            label = f'{archive_label}/{pathlib.Path(member).name}'
            dependencies.append(object_path)
            modules.append((label, object_path))

    def inspect(module):
        label, object_path = module
        return inventory_module(label, disassemble(args.clang, object_path))

    rows = []
    with concurrent.futures.ThreadPoolExecutor(
        max_workers=min(16, os.cpu_count() or 1)
    ) as executor:
        for module_rows in executor.map(inspect, modules):
            rows.extend(module_rows)

    return MANIFEST_HEADER + '\n'.join(sorted(rows)) + '\n', dependencies


def verify_required_boundaries(inventory):
    errors = []
    for description, fragments in REQUIRED_BOUNDARIES.items():
        if not any(
            all(fragment in row for fragment in fragments)
            for row in inventory.splitlines()
        ):
            errors.append(description)
    if errors:
        raise RuntimeError(
            'CFI callback boundary invariants failed:\n- ' +
            '\n- '.join(errors)
        )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--clang', required=True, type=pathlib.Path)
    parser.add_argument('--llvm-ar', required=True, type=pathlib.Path)
    parser.add_argument(
        '--build-dir', type=pathlib.Path, default=pathlib.Path('.')
    )
    parser.add_argument(
        '--object', action='append', type=parse_named_path, default=[]
    )
    parser.add_argument(
        '--ninja-objects',
        action='append',
        type=parse_ninja_objects,
        default=[],
    )
    parser.add_argument(
        '--thin-archive', action='append', type=parse_named_path, default=[]
    )
    parser.add_argument('--manifest', required=True, type=pathlib.Path)
    parser.add_argument('--stamp', type=pathlib.Path)
    parser.add_argument('--depfile', type=pathlib.Path)
    parser.add_argument('--update', action='store_true')
    args = parser.parse_args()

    verify_inventory_classifier()
    actual, dependencies = build_inventory(args)
    verify_required_boundaries(actual)
    if args.update:
        args.manifest.write_text(actual)
        return

    expected = args.manifest.read_text()
    if actual != expected:
        diff = ''.join(difflib.unified_diff(
            expected.splitlines(keepends=True),
            actual.splitlines(keepends=True),
            fromfile=str(args.manifest),
            tofile='current ThinLTO callback inventory',
        ))
        print(
            'CFI callback boundary inventory changed. Review every new or '
            "changed indirect call, update Electron's scoped ignorelist when "
            'the callee may come from an uninstrumented addon, then regenerate '
            "the manifest with this script's --update option.",
            file=sys.stderr,
        )
        print(diff, file=sys.stderr)
        return 1

    if args.stamp:
        args.stamp.parent.mkdir(parents=True, exist_ok=True)
        args.stamp.touch()
    if args.depfile:
        if not args.stamp:
            parser.error('--depfile requires --stamp')
        args.depfile.parent.mkdir(parents=True, exist_ok=True)
        escaped_dependencies = [
            str(path).replace(' ', '\\ ') for path in dependencies
        ]
        args.depfile.write_text(
            f'{args.stamp}: {" ".join(escaped_dependencies)}\n'
        )
    return 0


if __name__ == '__main__':
    sys.exit(main())
